const ids = { GlowSkin: 'ctr-glowskin', Ledgerly: 'ctr-ledgerly', Northdesk: 'ctr-northdesk' };
for (const c of contracts) {
  out.push(`insert into contracts (id,user_id,brand,filename,body,message,status) values (${q(ids[c.brand])}, ${U}, ${q(c.brand)}, ${q(c.file)}, ${q(c.text)}, ${q(c.msg)}, ${q(c.status)}) on conflict (id) do nothing;`);
  out.push('');
}

