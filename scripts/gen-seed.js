// Generates supabase/seed.sql from counter.html so the seeded text is copied verbatim, never retyped.
// Run: node scripts/gen-seed.js
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const html = fs.readFileSync(path.join(root, 'counter.html'), 'utf8');

// 1) seed constants defined at the top of the app script
const top = html.slice(html.indexOf('const GLOW_MSG'), html.indexOf('const EVAL_PROMPTS'));
const { GLOW_MSG, GLOW_CON, FIN_MSG, WELL_MSG } = new Function(top + '\nreturn {GLOW_MSG,GLOW_CON,FIN_MSG,WELL_MSG};')();

// 2) the sample Ledgerly and Northdesk contracts defined in S.contracts
